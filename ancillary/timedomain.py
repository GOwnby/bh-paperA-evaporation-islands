"""Time-domain cross-check of the trapped-mode spectrum: finite-difference evolution of
  d^2 psi/dt^2 = d^2 psi/dx^2 - V_l(r(x)) psi
on the horizonless Hayward metric (units ell = 1), Dirichlet (regularity) at r=0 (x=0),
first-order outgoing (Sommerfeld) condition at the outer boundary, Gaussian initial pulse.
Defaults reproduce the paper: l=2, M=0.90 M*, Nx=6000, T=2200.  Output: ancillary/output/td_l{l}_nx{Nx}.npz
(signal at x=25 versus t; ~6 MB, regenerated by verify.sh, not tracked in git).  Analysed by fit_timedomain.py.
Usage: python3 timedomain.py [--l 2] [--mfrac 0.90] [--nx 6000] [--tfinal 2200]   (about 25 s for the defaults; 10 s for --nx 3000; 2.5 min for --nx 12000)
"""
import argparse, os, sys, time
import numpy as np
from scipy.integrate import cumulative_trapezoid
from scipy.interpolate import interp1d
from _util import OUT

ap = argparse.ArgumentParser()
ap.add_argument("--l", type=int, default=2)
ap.add_argument("--mfrac", type=float, default=0.90)
ap.add_argument("--nx", type=int, default=6000)
ap.add_argument("--tfinal", type=float, default=2200.0)
a = ap.parse_args()

l_scale = 1.0; Mstar = 3*np.sqrt(3)/4*l_scale
M = a.mfrac*Mstar
l = a.l


def f(r): return 1 - 2*M*r**2/(r**3+2*M*l_scale**2)
def fp(r, h=1e-6): return (f(r+h)-f(r-h))/(2*h)
def V(r): return f(r)*(l*(l+1)/r**2 + fp(r)/r)


# r(x) via the tortoise coordinate x(r) = int_0^r dr'/f(r')   (no horizon: x(0)=0)
rgrid = np.linspace(1e-5, 80, 400000)
xgrid = cumulative_trapezoid(1.0/f(rgrid), rgrid, initial=0.0)
r_of_x = interp1d(xgrid, rgrid, kind='cubic', bounds_error=False, fill_value=(0.0, rgrid[-1]))
xmax = xgrid[-1]
print(f"x range: [0, {xmax:.2f}]  (r up to {rgrid[-1]:.1f})")

Nx = a.nx
xarr = np.linspace(0, min(xmax, 90), Nx)
dx = xarr[1]-xarr[0]
rarr = r_of_x(xarr)
Varr = V(np.clip(rarr, 1e-6, None))
Varr[0] = Varr[1]*3 - Varr[2]*2   # extrapolate near the (regular, steep) origin

dt = 0.4*dx
Nt = int(a.tfinal/dt)
print(f"l={l}, M/M*={a.mfrac}, Nx={Nx}, dx={dx:.4f}, dt={dt:.4f}, Nt={Nt}")

x0 = 20.0; sigma = 2.0
psi = np.exp(-(xarr-x0)**2/(2*sigma**2))
psi[0] = 0.0   # regularity (Dirichlet) at the origin, required for l>=1

lap = np.zeros_like(psi)
lap[1:-1] = (psi[2:]-2*psi[1:-1]+psi[:-2])/dx**2
psi_tt0 = lap - Varr*psi
psi_prev = psi.copy()
psi_cur = psi + 0.5*dt**2*psi_tt0     # first step from psi_t(0)=0
psi_cur[0] = 0.0

obs_x = 25.0
obs_i = np.argmin(np.abs(xarr-obs_x))
signal = np.empty(Nt)

t0 = time.time()
for n in range(Nt):
    lap = np.zeros_like(psi_cur)
    lap[1:-1] = (psi_cur[2:]-2*psi_cur[1:-1]+psi_cur[:-2])/dx**2
    psi_new = 2*psi_cur - psi_prev + dt**2*(lap - Varr*psi_cur)
    psi_new[0] = 0.0
    psi_new[-1] = psi_cur[-1] - (dt/dx)*(psi_cur[-1]-psi_cur[-2])   # d/dt psi + d/dx psi = 0
    signal[n] = psi_cur[obs_i]
    psi_prev, psi_cur = psi_cur, psi_new
# (wall-clock times of all scripts are recorded in verification/timings.txt; not printed here so that the log is deterministic)

tarr = np.arange(Nt)*dt
fn = os.path.join(OUT, f"td_l{l}_nx{Nx}.npz")
np.savez(fn, t=tarr, s=signal)
print("saved", os.path.relpath(fn, os.path.dirname(OUT)), ", signal length", Nt)
